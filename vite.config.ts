import { defineConfig, type Plugin } from 'vite';
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Builds src/ into theme/assets.
 *
 * Shopify theme assets must be a flat folder, so:
 * - entries keep stable names (kuki-core.js, island-*.js) and get cache-busted by
 *   Shopify's `asset_url` (?v=…);
 * - shared chunks get content hashes, so relative imports between them are safe forever;
 * - critical.css is turned into snippets/critical-css.liquid and inlined in <head>.
 */

const ASSETS = 'theme/assets';
const SNIPPETS = 'theme/snippets';

export const entries: Record<string, string> = {
  'kuki-core': 'src/core/main.ts',
  'island-shelf2d': 'src/islands/shelf2d/index.ts',
  'island-shelf3d': 'src/islands/shelf3d/index.tsx',
  'island-tastemap': 'src/islands/tastemap/index.ts',
  'island-dabba': 'src/islands/dabba/index.ts',
  'island-gifting': 'src/islands/gifting/index.ts',
  'island-twist-send': 'src/islands/twist-send/index.ts',
  critical: 'src/styles/critical.css',
  kuki: 'src/styles/kuki.css',
};

/** Only build entries whose source exists yet (islands land phase by phase). */
function existingEntries(): Record<string, string> {
  return Object.fromEntries(Object.entries(entries).filter(([, file]) => existsSync(file)));
}

/** Remove previously built hashed chunks so theme/assets never accumulates stale files. */
function cleanBuiltFiles(): Plugin {
  return {
    name: 'kuki:clean-built-files',
    buildStart() {
      if (!existsSync(ASSETS)) return;
      for (const file of readdirSync(ASSETS)) {
        if (/^chunk-.+\.js(\.map)?$/.test(file) || /^(kuki-core|island-[\w-]+)\.js\.map$/.test(file)) {
          rmSync(join(ASSETS, file));
        }
      }
    },
  };
}

/** Turn the built critical.css into an inline Liquid snippet. */
function inlineCriticalCss(): Plugin {
  return {
    name: 'kuki:inline-critical-css',
    writeBundle() {
      const css = join(ASSETS, 'critical.css');
      if (!existsSync(css)) return;
      const content = readFileSync(css, 'utf8').trim();
      writeFileSync(
        join(SNIPPETS, 'critical-css.liquid'),
        `{%- comment -%} Generated by vite.config.ts from src/styles/critical.css. Do not edit. {%- endcomment -%}\n<style>{% raw %}${content}{% endraw %}</style>\n`,
      );
      rmSync(css);
      const stub = join(ASSETS, 'critical.js');
      if (existsSync(stub)) rmSync(stub);
    },
  };
}

/** CSS-only entries can leave an empty JS stub behind; delete it. */
function removeCssStubs(): Plugin {
  return {
    name: 'kuki:remove-css-stubs',
    writeBundle() {
      for (const name of ['kuki.js', 'critical.js']) {
        const file = join(ASSETS, name);
        if (existsSync(file) && readFileSync(file, 'utf8').trim().length < 80) rmSync(file);
      }
    },
  };
}

export default defineConfig(({ mode }) => {
  const dev = mode === 'development';
  return {
    publicDir: false,
    css: {
      transformer: 'lightningcss',
      lightningcss: {
        // Mid-range Android Chrome, iOS Safari 16+, recent desktop browsers.
        targets: { chrome: 105 << 16, safari: (16 << 16) | (4 << 8), firefox: 110 << 16 },
      },
    },
    build: {
      outDir: ASSETS,
      emptyOutDir: false,
      assetsDir: '',
      target: ['es2022', 'chrome105', 'safari16'],
      modulePreload: false,
      cssCodeSplit: true,
      cssMinify: 'lightningcss',
      minify: !dev,
      sourcemap: dev,
      reportCompressedSize: !dev,
      chunkSizeWarningLimit: 900,
      rollupOptions: {
        input: existingEntries(),
        preserveEntrySignatures: 'exports-only',
        output: {
          entryFileNames: '[name].js',
          chunkFileNames: 'chunk-[name]-[hash].js',
          assetFileNames: '[name][extname]',
        },
      },
    },
    plugins: [cleanBuiltFiles(), inlineCriticalCss(), removeCssStubs()],
  };
});
